import test from 'node:test'
import assert from 'node:assert/strict'
import {DEMO_PASSWORD, DEMO_RESET_CODE, LOGIN_LOCK, MAX_CODE_ATTEMPTS, MAX_LOGIN_ATTEMPTS, RESEND_COOLDOWN, RESET_CODE_TTL, createAuthApi, maskEmail} from '../src/api/authService.js'

const setup = () => { let time = 1e12; const api = createAuthApi({now: () => time}); return {api, advance: ms => { time += ms }} }
const reset = (api, ticket, code = DEMO_RESET_CODE) => api.resetPassword({ticket, code, password: 'secret1', confirm: 'secret1'})

test('email, phone and username all send the code to the bound email, masked', async () => {
  const {api} = setup()
  assert.equal(maskEmail('demo.trader@newquant.test'), 'de***@newquant.test')
  assert.equal(maskEmail('ab@x.io'), 'a***@x.io')
  assert.equal((await api.requestResetCode({method: 'email', identifier: 'Demo.Trader@newquant.test'})).maskedEmail, 'de***@newquant.test')
  assert.equal((await api.requestResetCode({method: 'phone', dial: '+886', identifier: '912 345 678'})).maskedEmail, 'al***@newquant.test')
  const byName = await api.requestResetCode({method: 'username', identifier: 'demo_trader'})
  assert.equal(byName.maskedEmail, 'de***@newquant.test', 'username shares the account with the email above but has its own cooldown key')
  assert.equal(byName.resendIn, RESEND_COOLDOWN / 1000)
})

test('validation, unknown accounts, missing bound email and the resend cooldown', async () => {
  const {api, advance} = setup()
  await assert.rejects(api.requestResetCode({method: 'email', identifier: ' '}), {code: 'auth.enterEmail'})
  await assert.rejects(api.requestResetCode({method: 'email', identifier: 'nope'}), {code: 'profile.bindEmailPage.invalidEmail'})
  await assert.rejects(api.requestResetCode({method: 'phone', dial: '+1', identifier: '12a'}), {code: 'auth.reset.invalidPhone'})
  await assert.rejects(api.requestResetCode({method: 'username', identifier: 'nomail'}), {code: 'auth.reset.noBoundEmail'})
  await assert.rejects(api.requestResetCode({method: 'phone', dial: '+852', identifier: '61234567'}), {code: 'auth.reset.noBoundEmail'})
  await assert.rejects(api.requestResetCode({method: 'username', identifier: 'ghost'}), {code: 'auth.reset.accountNotFound'})
  await assert.rejects(api.requestResetCode({method: 'email', identifier: 'nobody@example.com'}), {code: 'auth.reset.accountNotFound'})
  await assert.rejects(api.requestResetCode({method: 'phone', dial: '+1', identifier: '3333333'}), {code: 'auth.reset.accountNotFound'})
  await api.requestResetCode({method: 'username', identifier: 'alice'})
  advance(20000)
  await assert.rejects(api.requestResetCode({method: 'username', identifier: 'ALICE'}), {code: 'auth.reset.tooSoon', params: {count: 40}})
  advance(40000)
  assert.ok((await api.requestResetCode({method: 'username', identifier: 'alice'})).ticket)
})

test('reset checks passwords, then the code; resend replaces the ticket; attempts and expiry are enforced', async () => {
  const {api, advance} = setup()
  const first = await api.requestResetCode({method: 'username', identifier: 'alice'})
  await assert.rejects(api.resetPassword({ticket: first.ticket, code: DEMO_RESET_CODE, password: '123', confirm: '123'}), {code: 'auth.passwordTooShort'})
  await assert.rejects(api.resetPassword({ticket: first.ticket, code: DEMO_RESET_CODE, password: 'secret1', confirm: 'secret2'}), {code: 'auth.reset.mismatch'})
  await assert.rejects(reset(api, first.ticket, '12'), {code: 'auth.reset.codeFormat'})
  advance(RESEND_COOLDOWN)
  const second = await api.requestResetCode({method: 'username', identifier: 'alice'})
  await assert.rejects(reset(api, first.ticket), {code: 'auth.reset.codeExpired'}, 'a resend voids the old ticket')
  for (let i = 1; i < MAX_CODE_ATTEMPTS; i++) await assert.rejects(reset(api, second.ticket, '000000'), {code: 'auth.reset.invalidCode'})
  await assert.rejects(reset(api, second.ticket, '000000'), {code: 'auth.reset.tooManyAttempts'})
  await assert.rejects(reset(api, second.ticket), {code: 'auth.reset.tooManyAttempts'}, 'locked even with the right code')
  advance(RESEND_COOLDOWN)
  const third = await api.requestResetCode({method: 'username', identifier: 'alice'})
  assert.deepEqual(await reset(api, third.ticket), {done: true})
  assert.equal(api.passwordOf('U1002'), 'secret1')
  await assert.rejects(reset(api, third.ticket), {code: 'auth.reset.codeExpired'}, 'a ticket works once')
  advance(RESEND_COOLDOWN)
  const late = await api.requestResetCode({method: 'username', identifier: 'alice'})
  advance(RESET_CODE_TTL)
  await assert.rejects(reset(api, late.ticket), {code: 'auth.reset.codeExpired'})
})

test('login reports unknown accounts, wrong passwords with attempts left, and locks after too many', async () => {
  const {api, advance} = setup()
  const login = (password, request = {method: 'username', identifier: 'alice'}) => api.loginWithPassword({...request, password})
  await assert.rejects(login('x', {method: 'username', identifier: 'ghost'}), {code: 'auth.loginFail.accountNotFound'})
  await assert.rejects(login('x', {method: 'phone', dial: '+1', identifier: '3333333'}), {code: 'auth.loginFail.accountNotFound'})
  await assert.rejects(login(''), {code: 'auth.enterPassword'})
  assert.deepEqual(await login(DEMO_PASSWORD, {method: 'email', identifier: 'ALICE.chen@newquant.test'}), {id: 'U1002', username: 'alice'})
  assert.equal((await login(DEMO_PASSWORD, {method: 'phone', dial: '+886', identifier: '912345678'})).id, 'U1002')
  for (let left = MAX_LOGIN_ATTEMPTS - 1; left > 0; left--) await assert.rejects(login('wrong'), {code: 'auth.loginFail.wrongPassword', params: {count: left}})
  await assert.rejects(login('wrong'), {code: 'auth.loginFail.locked', params: {minutes: 15}})
  await assert.rejects(login(DEMO_PASSWORD), {code: 'auth.loginFail.locked'}, 'the right password waits for the lock')
  advance(LOGIN_LOCK)
  assert.equal((await login(DEMO_PASSWORD)).id, 'U1002')
})

test('a password reset changes the login password and clears the lock', async () => {
  const {api} = setup()
  const login = password => api.loginWithPassword({method: 'username', identifier: 'demo_trader', password})
  for (let i = 0; i < MAX_LOGIN_ATTEMPTS; i++) await login('wrong').catch(() => {})
  await assert.rejects(login(DEMO_PASSWORD), {code: 'auth.loginFail.locked'})
  const {ticket} = await api.requestResetCode({method: 'username', identifier: 'demo_trader'})
  await reset(api, ticket)
  await assert.rejects(login(DEMO_PASSWORD), {code: 'auth.loginFail.wrongPassword'})
  assert.equal((await login('secret1')).id, 'U1001')
})

test('register reports taken identifiers, username format and short passwords; the new account logs in and resets', async () => {
  const {api} = setup()
  await assert.rejects(api.registerAccount({method: 'email', identifier: 'demo.trader@newquant.test', password: 'secret1'}), {code: 'auth.registerFail.emailTaken'})
  await assert.rejects(api.registerAccount({method: 'phone', dial: '+886', identifier: '912345678', password: 'secret1'}), {code: 'auth.registerFail.phoneTaken'})
  await assert.rejects(api.registerAccount({method: 'username', identifier: 'Alice', password: 'secret1'}), {code: 'auth.registerFail.usernameTaken'})
  await assert.rejects(api.registerAccount({method: 'username', identifier: 'a b', password: 'secret1'}), {code: 'auth.registerFail.usernameFormat'})
  await assert.rejects(api.registerAccount({method: 'email', identifier: 'bad', password: 'secret1'}), {code: 'profile.bindEmailPage.invalidEmail'})
  await assert.rejects(api.registerAccount({method: 'email', identifier: 'new@example.com', password: '123'}), {code: 'auth.passwordTooShort'})
  assert.ok((await api.registerAccount({method: 'email', identifier: 'new@example.com', password: 'secret1'})).id)
  await assert.rejects(api.registerAccount({method: 'email', identifier: 'NEW@example.com', password: 'secret1'}), {code: 'auth.registerFail.emailTaken'})
  assert.ok(await api.loginWithPassword({method: 'email', identifier: 'new@example.com', password: 'secret1'}))
  assert.equal((await api.requestResetCode({method: 'email', identifier: 'new@example.com'})).maskedEmail, 'ne***@example.com')
  await api.registerAccount({method: 'username', identifier: 'fresh_user', password: 'secret1'})
  await assert.rejects(api.requestResetCode({method: 'username', identifier: 'fresh_user'}), {code: 'auth.reset.noBoundEmail'})
  await api.registerAccount({method: 'phone', dial: '+44', identifier: '7700900123', password: 'secret1'})
  assert.ok(await api.loginWithPassword({method: 'phone', dial: '+44', identifier: '7700 900123', password: 'secret1'}))
})
